#!/usr/bin/env bash
# lifecycle-drift.sh: the handlers carry a copy of the library, and the copy is what runs.
#
#   bash tests/coordinator/lifecycle-drift.sh
#
# `eidolon` compiles each `tools/*.rn` as one source file and `lib/` only in front of
# workflows, so every handler that needs the policy repeats it. That makes two texts
# where there is one intent: `coordinator/lib/lifecycle.rn` is what
# `lifecycle-shape.sh` tests, and the handler's copy is what the dispatcher actually
# executes. A green test over a library the handler does not carry is exactly the
# failure this file exists to refuse.
#
# The region is generated by `lifecycle-copies.py --write` and this compares it **by
# region, not by name**: a renamed copy is still part of the region and still has to
# equal the library's text, so renaming one does not exempt it.
#
# Exit 0 when every region matches, 1 on divergence (the first differing function is
# named), 3 when there is nothing to compare — which fails closed, because a guard that
# compared nothing must not read as a pass.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
exec python3 "$here/lifecycle-copies.py" --check
